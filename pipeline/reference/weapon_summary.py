"""Rewrites the summary table in data/reference/weapons.md from the weapon tables.

Run from the repo root: uv run pipeline/reference/weapon_summary.py
Standard library only. tests/test_weapons.py fails if the table is out of date.
"""

import csv
from pathlib import Path

REFERENCE = Path(__file__).resolve().parents[2] / "data" / "reference"
START = "<!-- summary: generated by pipeline/reference/weapon_summary.py -->"
END = "<!-- end summary -->"

MEASURES = (
    ("length", "Length (m)"),
    ("wingspan", "Wingspan (m)"),
    ("diameter", "Diameter (m)"),
    ("warhead", "Warhead (kg)"),
    ("range", "Range (km)"),
    ("speed", "Speed as published"),
)


def read(name, folder=REFERENCE):
    with (folder / name).open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def _number(value):
    return f"{value:,.3f}".rstrip("0").rstrip(".")


def span(rows):
    """The widest span of rows that share a unit."""
    low = min(float(r["low"]) for r in rows)
    high = max(float(r["high"]) for r in rows)
    return _number(low) if low == high else f"{_number(low)}–{_number(high)}"


def cell(rows, kinds):
    """One table cell. † marks a figure that only Wikipedia pages support."""
    known = [r for r in rows if r["low"]]
    if not known:
        return "unknown"
    parts = []
    for unit in dict.fromkeys(r["unit"] for r in known):
        text = span([r for r in known if r["unit"] == unit])
        if unit == "Mach":
            text = f"Mach {text}"
        elif unit in ("km/h", "m/s"):
            text = f"{text} {unit}"
        parts.append(text)
    mark = " †" if all(kinds[r["source"]] == "encyclopedia" for r in known) else ""
    return "; ".join(parts) + mark


def render(folder=REFERENCE):
    members = read("weapon_members.csv", folder)
    figures = read("weapon_figures.csv", folder)
    kinds = {r["source"]: r["kind"] for r in read("weapon_sources.csv", folder)}
    labels = {r["class"]: r["label"] for r in read("weapon_classes.csv", folder)}
    lines = []
    for class_id in dict.fromkeys(m["class"] for m in members):
        headings = ["Weapon", "Speed category", *(label for _, label in MEASURES)]
        lines += [
            f"### {labels[class_id]}",
            "",
            "| " + " | ".join(headings) + " |",
            "|" + " --- |" * len(headings),
        ]
        for m in members:
            if m["class"] != class_id:
                continue
            cells = [m["name"], m["speed_category"]]
            for measure, _ in MEASURES:
                rows = [
                    r for r in figures
                    if r["member"] == m["member"] and r["measure"] == measure
                ]
                cells.append(cell(rows, kinds))
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    return "\n".join(lines).rstrip()


def replace_summary(document, table):
    before, rest = document.split(START)
    _, after = rest.split(END)
    return f"{before}{START}\n\n{table}\n\n{END}{after}"


if __name__ == "__main__":
    path = REFERENCE / "weapons.md"
    text = replace_summary(path.read_text(encoding="utf-8"), render())
    path.write_text(text, encoding="utf-8", newline="\n")
