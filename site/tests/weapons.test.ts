import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import {
  allUnknown,
  classOnlySearch,
  parseWeapons,
  PRIMER_CLASS_IDS,
  primerCard,
  primerHash,
  wikipediaOnly,
} from "../src/weapons/weaponData.ts";

const read = (name: string) => readFileSync(new URL(`../../data/reference/${name}`, import.meta.url), "utf8");

const membersCsv = read("weapon_members.csv");
const figuresCsv = read("weapon_figures.csv");
const sourcesCsv = read("weapon_sources.csv");
const { members, sources } = parseWeapons(membersCsv, figuresCsv, sourcesCsv);

test("each of the five classes has members, and mixed has no card", () => {
  assert.equal(PRIMER_CLASS_IDS.length, 5);
  assert.deepEqual([...new Set(members.map((member) => member.classId))], PRIMER_CLASS_IDS);
});

// The summary is generated by Python and checked there, so agreeing with it
// checks that the page's spans and Wikipedia-only marks follow the same rules.
test("every span and Wikipedia-only mark matches the summary in weapons.md", () => {
  const rows = new Map(
    read("weapons.md")
      .split("<!-- summary:")[1]!
      .split("<!-- end summary -->")[0]!
      .split(/\r?\n/)
      .filter((line) => line.startsWith("| ") && !line.startsWith("| Weapon") && !line.startsWith("| ---"))
      .map((line) => line.slice(2, -2).split(" | "))
      .map(([name, ...cells]) => [name!, cells] as const),
  );
  assert.equal(rows.size, members.length);
  for (const member of members) {
    const cells = member.measures.map((measure) => {
      if (measure.value === null) return "unknown";
      // The summary gives the unit in the column heading, except for speed.
      const value = measure.id === "speed" ? measure.value : measure.value.replace(/ (m|kg|km)$/, "");
      return wikipediaOnly(measure.sources) ? `${value} †` : value;
    });
    assert.deepEqual([member.speedCategory.text, ...cells], rows.get(member.name), member.name);
  }
});

test("every figure and statement is cited or marked unknown", () => {
  for (const member of members) {
    for (const measure of member.measures) {
      const unknown = measure.value === null;
      assert.equal(unknown, !measure.sources.length, `${member.id} ${measure.id}`);
      assert.equal(unknown, !!measure.unknownReason, `${member.id} ${measure.id}`);
      assert.equal(unknown, !measure.figures.length, `${member.id} ${measure.id}`);
    }
    for (const field of [member.role, member.platform, member.speedCategory]) {
      assert.equal(field.text === "unknown", !field.sources.length, member.id);
    }
  }
  assert.ok(allUnknown(members.find((member) => member.id === "unknown_missile")!));
  assert.ok(!allUnknown(members.find((member) => member.id === "dan_t")!));
});

test("each source figure keeps its own value and note", () => {
  const range = members.find((member) => member.id === "kh_101")!.measures.find((measure) => measure.id === "range")!;
  assert.equal(range.value, "2,500–5,500 km");
  assert.deepEqual(
    range.figures.map((figure) => [figure.source.id, figure.value, figure.note]),
    [
      ["csis-kh101", "2,500–2,800 km", ""],
      ["wp-kh101", "3,500 km", ""],
      ["gur-kh101", "5,500 km", "Upper limit."],
    ],
  );
  assert.ok(sources.every((source) => source.url.startsWith("https://")));
});

test("a table with an uncited, misfiled or missing row is rejected", () => {
  const parse = (figures: string, list = membersCsv) => () => parseWeapons(list, figures, sourcesCsv);
  const swap = (csv: string, from: string, to: string) => {
    assert.ok(csv.includes(from), from);
    return csv.replace(from, to);
  };
  const row = "shahed_136,length,3.5,3.5,m,wp-shahed,";
  assert.throws(parse(swap(figuresCsv, row, "shahed_136,length,3.5,3.5,m,,")), /unknown source/);
  assert.throws(parse(swap(figuresCsv, row, "shahed_136,length,3.5,3.5,kg,wp-shahed,")), /wrong unit/);
  assert.throws(parse(swap(figuresCsv, row, "shahed_136,length,,,,,Not found.")), /one row/);
  assert.throws(parse(`${figuresCsv.trimEnd()}\nshahed_136,lenght,1,1,m,wp-shahed,\n`), /matches no member and measure/);
  assert.throws(parse(swap(figuresCsv, "shahed_136,diameter,,,,,", "shahed_136,diameter_,,,,,")), /has no row/);
  assert.throws(
    parse(figuresCsv, swap(membersCsv, "One-way attack drone,csis-shahed;wp-shahed", "One-way attack drone,")),
    /must be cited/,
  );
});

test("a class's route and chart link", () => {
  assert.equal(primerHash(), "#weapons");
  assert.equal(primerHash("cruise"), "#weapons-cruise");
  assert.equal(primerHash("mixed"), "#weapons");
  assert.equal(primerCard("#weapons-cruise"), "cruise");
  for (const hash of ["#weapons", "#weapons-mixed", "#weapons-nope", "#attacks", ""]) assert.equal(primerCard(hash), null);
  assert.equal(classOnlySearch("", "cruise"), "?classes=cruise");
  assert.equal(
    classOnlySearch("?from=2024-01&classes=ballistic,mixed&oblasts=UA-63,UA-30", "cruise"),
    "?from=2024-01&classes=cruise&oblasts=UA-63,UA-30",
  );
});
